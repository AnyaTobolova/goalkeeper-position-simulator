// Порядок фиксируется на одно прохождение; обе позиции правильного ответа
// встречаются даже при случайно одинаковых перестановках всех карточек.
export function shuffleQuizAnswers(cards: RulesQuizCard[], random: () => number = Math.random): RulesQuizCard[] {
  const shuffled = cards.map((card) => ({ ...card, answers: random() < 0.5 ? [...card.answers].reverse() : [...card.answers] }));
  if (shuffled.length > 1 && shuffled.every((card) => card.answers.findIndex((answer) => answer.correct) === shuffled[0].answers.findIndex((answer) => answer.correct))) {
    shuffled[shuffled.length - 1].answers.reverse();
  }
  return shuffled;
}
